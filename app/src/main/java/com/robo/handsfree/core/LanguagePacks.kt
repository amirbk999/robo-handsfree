    /** Resolves an app name spoken in any language to the label Android knows. */
    fun canonicalApp(name: String): String = APP_ALIASES[normalizeText(name)] ?: name

    /** The pack for a locale tag, or null for automatic. */
    fun forTag(tag: String): LanguagePack? {
        if (tag.isBlank() || tag.equals("auto", ignoreCase = true)) return null
        return spokenLanguages.firstOrNull {
            it.tag.equals(tag, ignoreCase = true) ||
                it.code.equals(tag.substringBefore('-'), ignoreCase = true)
        }
    }
