package com.robo.handsfree.core

/**
 * The vocabulary behind [LanguageMatcher]: which words in which language mean which command.
 *
 * Every language is searched at once, so mixed sentences ("Mummy ko WhatsApp kholo") work and
 * a phone whose recogniser is set to one language can still understand borrowed words.
 */
class PackBuilder(
    private val code: String,
    private val englishName: String,
    private val nativeName: String,
    private val tag: String
) {
    private val triggers = mutableListOf<Pair<String, Intent>>()
    private val prefixes = mutableListOf<String>()
    private val suffixes = mutableListOf<String>()
    private val connectors = mutableListOf<String>()

    fun add(intent: Intent, vararg words: String) {
        words.forEach { word ->
            val folded = normalizeText(word)
            if (folded.isNotEmpty()) triggers += folded to intent
        }
    }

    fun open(vararg w: String) = add(Intent.OPEN, *w)
    fun call(vararg w: String) = add(Intent.CALL, *w)
    fun message(vararg w: String) = add(Intent.MESSAGE, *w)
    fun alarm(vararg w: String) = add(Intent.ALARM, *w)
    fun timer(vararg w: String) = add(Intent.TIMER, *w)
    fun reminder(vararg w: String) = add(Intent.REMINDER, *w)
    fun note(vararg w: String) = add(Intent.NOTE, *w)
    fun readNotes(vararg w: String) = add(Intent.READ_NOTES, *w)
    fun flashlight(vararg w: String) = add(Intent.FLASHLIGHT, *w)
    fun volumeUp(vararg w: String) = add(Intent.VOLUME_UP, *w)
    fun volumeDown(vararg w: String) = add(Intent.VOLUME_DOWN, *w)
    fun mute(vararg w: String) = add(Intent.MUTE, *w)
    fun unmute(vararg w: String) = add(Intent.UNMUTE, *w)
    fun brightnessUp(vararg w: String) = add(Intent.BRIGHTNESS_UP, *w)
    fun brightnessDown(vararg w: String) = add(Intent.BRIGHTNESS_DOWN, *w)
    fun screenshot(vararg w: String) = add(Intent.SCREENSHOT, *w)
    fun camera(vararg w: String) = add(Intent.CAMERA, *w)
    fun scrollDown(vararg w: String) = add(Intent.SCROLL_DOWN, *w)
    fun scrollUp(vararg w: String) = add(Intent.SCROLL_UP, *w)
    fun back(vararg w: String) = add(Intent.BACK, *w)
    fun home(vararg w: String) = add(Intent.HOME, *w)
    fun recents(vararg w: String) = add(Intent.RECENTS, *w)
    fun battery(vararg w: String) = add(Intent.BATTERY, *w)
    fun time(vararg w: String) = add(Intent.TIME, *w)
    fun date(vararg w: String) = add(Intent.DATE, *w)
    fun search(vararg w: String) = add(Intent.SEARCH, *w)
    fun navigate(vararg w: String) = add(Intent.NAVIGATE, *w)
    fun play(vararg w: String) = add(Intent.PLAY, *w)
    fun pause(vararg w: String) = add(Intent.PAUSE, *w)
    fun next(vararg w: String) = add(Intent.NEXT, *w)
    fun previous(vararg w: String) = add(Intent.PREVIOUS, *w)
    fun help(vararg w: String) = add(Intent.HELP, *w)
    fun stop(vararg w: String) = add(Intent.STOP, *w)
    fun start(vararg w: String) = add(Intent.START, *w)
    fun lock(vararg w: String) = add(Intent.LOCK, *w)
    fun readScreen(vararg w: String) = add(Intent.READ_SCREEN, *w)
    fun tap(vararg w: String) = add(Intent.TAP, *w)
    fun type(vararg w: String) = add(Intent.TYPE, *w)
    fun notifications(vararg w: String) = add(Intent.NOTIFICATIONS, *w)
    fun quickSettings(vararg w: String) = add(Intent.QUICK_SETTINGS, *w)
    fun settings(vararg w: String) = add(Intent.SETTINGS, *w)
    fun wifi(vararg w: String) = add(Intent.WIFI, *w)
    fun bluetooth(vararg w: String) = add(Intent.BLUETOOTH, *w)
    fun airplane(vararg w: String) = add(Intent.AIRPLANE, *w)
    fun data(vararg w: String) = add(Intent.DATA, *w)

    fun stripPrefix(vararg w: String) {
        w.forEach { prefixes += normalizeText(it) }
    }

    fun stripSuffix(vararg w: String) {
        w.forEach { suffixes += normalizeText(it) }
    }

    fun connect(vararg w: String) {
        w.forEach { connectors += normalizeText(it) }
    }

    fun build(): LanguagePack = LanguagePack(
        code = code,
        englishName = englishName,
        nativeName = nativeName,
        tag = tag,
        triggers = triggers.distinct().toList(),
        prefixes = prefixes.distinct(),
        suffixes = suffixes.distinct(),
        connectors = connectors.distinct()
    )
}

internal fun pack(
    code: String,
    english: String,
    native: String,
    tag: String,
    block: PackBuilder.() -> Unit
): LanguagePack = PackBuilder(code, english, native, tag).apply(block).build()

